"""ATT&CK Navigator layer export (enterprise domain only)."""

from __future__ import annotations

from typing import Any

from .palette import LEVEL_FILL
from .scoring import LEVEL_NAMES, Coverage

LEVEL_SCORES = {0: 0, 1: 33, 2: 66, 3: 100}
LEVEL_COLORS = LEVEL_FILL
GRADIENT = [LEVEL_FILL[n] for n in range(4)]


def build_layer(
    coverage: Coverage,
    name: str = "SIEM detection coverage",
    description: str = "",
) -> dict[str, Any]:
    """Build a Navigator 4.5 layer from ATT&CK coverage. Every matrix technique appears once."""
    if coverage.framework != "attack":
        raise ValueError("Navigator layers are only supported for ATT&CK (ATLAS has its own tooling)")

    best: dict[str, dict[str, Any]] = {}
    for cell in coverage.cells:
        best.setdefault(cell["id"], cell)

    techniques = []
    for tid, cell in best.items():
        level = cell["level"]
        comment = LEVEL_NAMES[level]
        if cell["rules"]:
            comment += " · rules: " + ", ".join(cell["rules"])
        techniques.append({"techniqueID": tid, "score": LEVEL_SCORES[level], "comment": comment})

    totals = coverage.totals
    if not description:
        description = (
            f"Generated by mitre-coverage-kit. {totals['distinct_covered']} of "
            f"{totals['distinct_techniques']} techniques have at least one working detection."
        )
    return {
        "name": name,
        "versions": {
            "attack": coverage.version.split(".")[0],
            "navigator": "5.1.0",
            "layer": "4.5",
        },
        "domain": "enterprise-attack",
        "description": description,
        "gradient": {"colors": list(GRADIENT), "minValue": 0, "maxValue": 100},
        "legendItems": [
            {"label": f"{LEVEL_NAMES[n]} ({LEVEL_SCORES[n]})", "color": LEVEL_COLORS[n]}
            for n in range(4)
        ],
        "techniques": techniques,
        "showTacticRowBackground": True,
        "selectTechniquesAcrossTactics": True,
        "layout": {"layout": "side", "showID": True, "showName": True},
    }
