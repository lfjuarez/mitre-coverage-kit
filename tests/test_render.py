import xml.etree.ElementTree as ET

from coveragekit import render, scoring
from coveragekit.rules import load_rules

NS = {"s": "http://www.w3.org/2000/svg"}


def parse(framework_package):
    cov = scoring.score(load_rules("examples/rules.csv"), framework_package)
    return cov, ET.fromstring(render.render_svg(cov))


def test_valid_xml_and_dimensions(attack):
    cov, root = parse(attack)
    assert root.tag == "{http://www.w3.org/2000/svg}svg"
    assert root.get("width") == "1100"
    assert int(root.get("height")) > 600


def test_one_rect_per_cell(attack, atlas):
    for package in (attack, atlas):
        cov, root = parse(package)
        cell_rects = [r for r in root.iter("{http://www.w3.org/2000/svg}rect") if r.find("s:title", NS) is not None]
        assert len(cell_rects) == len(cov.cells)


def test_contains_labels_legend_and_footer(attack):
    cov, root = parse(attack)
    text = " ".join("".join(t.itertext()) for t in root.iter("{http://www.w3.org/2000/svg}text"))
    for tactic in cov.tactics:
        assert tactic["tactic"] in text
    assert "generated by mitre-coverage-kit" in text
    assert "ATT&CK" in text and "v20.0" in text
    for level in ("None", "Low", "Medium", "High"):
        assert level in text
    assert "Techniques with at least one detection, by tactic" in text


def test_none_cells_have_hairline_stroke_and_header_is_rotated(attack):
    cov, root = parse(attack)
    none_cells = [
        r for r in root.iter("{http://www.w3.org/2000/svg}rect")
        if r.find("s:title", NS) is not None and r.get("fill") == "#f0efec"
    ]
    assert none_cells and all(r.get("stroke") == "#e1e0d9" for r in none_cells)
    rotated = [t for t in root.iter("{http://www.w3.org/2000/svg}text") if "rotate(-90)" in (t.get("transform") or "")]
    assert len(rotated) == len(cov.tactics)


def test_header_height_fits_longest_tactic(attack):
    cov, root = parse(attack)
    rotated = [t for t in root.iter("{http://www.w3.org/2000/svg}text") if "rotate(-90)" in (t.get("transform") or "")]
    longest = max(len(t["tactic"]) for t in cov.tactics)
    ys = [float(t.get("transform").split("translate(")[1].split(",")[1].split(")")[0]) for t in rotated]
    title_bottom = 76  # subtitle baseline
    # the text extends upward from its baseline by roughly len * 6.3 px
    assert all(y - longest * 6.3 > title_bottom for y in ys)
